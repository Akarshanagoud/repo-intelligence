"""Repository scanning.

The unglamorous part that determines whether everything downstream works. A
code-intelligence tool that indexes `node_modules`, minified bundles and
vendored dependencies produces search results nobody wants and architecture
graphs nobody recognises.

So the scanner is opinionated about exclusion:

* `.gitignore` is honoured, including nested ones, because the repository has
  already declared what is not source.
* Generated and vendored directories are excluded by default even when they
  are committed - a checked-in `vendor/` is still not your architecture.
* Binary files are detected by content (a NUL byte in the first 8 KB), not by
  extension, because the extension list is never complete.
* Minified and generated files are detected by shape: enormous mean line
  length, or a generation marker in the header.

Every exclusion is counted and reportable, so "why is my file missing?" has an
answer rather than a shrug.
"""
from __future__ import annotations

import fnmatch
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

#: Extension to language. Only languages the analyser can do something with.
LANGUAGES: dict[str, str] = {
    ".py": "python", ".pyi": "python",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".tsx": "typescript",
    ".go": "go",
    ".rs": "rust",
    ".java": "java",
    ".rb": "ruby",
    ".php": "php",
    ".c": "c", ".h": "c",
    ".cpp": "cpp", ".cc": "cpp", ".hpp": "cpp", ".cxx": "cpp",
    ".cs": "csharp",
    ".kt": "kotlin",
    ".swift": "swift",
    ".scala": "scala",
    ".sh": "shell", ".bash": "shell",
    ".sql": "sql",
    ".md": "markdown", ".rst": "markdown",
    ".yaml": "yaml", ".yml": "yaml",
    ".json": "json",
    ".toml": "toml",
}

#: Directories that are never source, whether or not they are gitignored.
EXCLUDED_DIRS = frozenset(
    {
        ".git", ".hg", ".svn", "node_modules", "vendor", "third_party",
        "__pycache__", ".pytest_cache", ".ruff_cache", ".mypy_cache", ".tox",
        "venv", ".venv", "env", "dist", "build", "target", "out",
        ".idea", ".vscode", ".next", ".nuxt", "coverage", "htmlcov",
        "site-packages", "bower_components", ".terraform", ".gradle",
    }
)

#: Filename patterns that are generated artefacts rather than authored code.
EXCLUDED_FILES = (
    "*.min.js", "*.min.css", "*.bundle.js", "*.map", "*.lock",
    "*_pb2.py", "*_pb2_grpc.py", "*.pb.go", "*.generated.*", "*.g.dart",
    "package-lock.json", "yarn.lock", "poetry.lock", "Cargo.lock",
)

_GENERATED_MARKER = re.compile(
    r"(?i)(@generated|do not edit|autogenerated|auto-generated|code generated by)"
)

TEST_PATTERNS = ("test_*.py", "*_test.py", "*.test.*", "*.spec.*", "*_test.go")
TEST_DIRS = frozenset({"tests", "test", "spec", "__tests__", "testing"})


@dataclass
class SourceFile:
    path: Path
    relative: str
    language: str
    size: int
    lines: int
    is_test: bool = False
    text: str = ""

    def to_dict(self, include_text: bool = False) -> dict[str, Any]:
        payload = {
            "path": self.relative,
            "language": self.language,
            "size": self.size,
            "lines": self.lines,
            "is_test": self.is_test,
        }
        if include_text:
            payload["text"] = self.text
        return payload


@dataclass
class ScanResult:
    root: Path
    files: list[SourceFile] = field(default_factory=list)
    #: reason -> count, so an unexpectedly empty scan is diagnosable.
    skipped: dict[str, int] = field(default_factory=dict)

    def by_language(self) -> dict[str, int]:
        counts: dict[str, int] = {}
        for file in self.files:
            counts[file.language] = counts.get(file.language, 0) + 1
        return dict(sorted(counts.items(), key=lambda kv: -kv[1]))

    def lines_by_language(self) -> dict[str, int]:
        counts: dict[str, int] = {}
        for file in self.files:
            counts[file.language] = counts.get(file.language, 0) + file.lines
        return dict(sorted(counts.items(), key=lambda kv: -kv[1]))

    @property
    def total_lines(self) -> int:
        return sum(f.lines for f in self.files)

    @property
    def test_files(self) -> list[SourceFile]:
        return [f for f in self.files if f.is_test]

    def summary(self) -> dict[str, Any]:
        return {
            "root": str(self.root),
            "files": len(self.files),
            "total_lines": self.total_lines,
            "languages": self.by_language(),
            "lines_by_language": self.lines_by_language(),
            "test_files": len(self.test_files),
            "skipped": dict(sorted(self.skipped.items(), key=lambda kv: -kv[1])),
        }


class GitignoreRules:
    """Minimal but honest .gitignore matcher.

    Supports the subset that actually appears in real files: directory-only
    patterns, anchored patterns, negation and glob wildcards. It does not
    implement the full spec - and says so rather than silently mismatching,
    because a scanner that claims full gitignore support and gets it subtly
    wrong is worse than one with documented limits.
    """

    def __init__(self, root: Path) -> None:
        self.root = root
        self.rules: list[tuple[str, bool, bool]] = []  # (pattern, negated, dir_only)
        self._load(root / ".gitignore", root)

    def _load(self, path: Path, base: Path) -> None:
        if not path.exists():
            return
        try:
            lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            return
        prefix = str(base.relative_to(self.root)).replace("\\", "/")
        for raw in lines:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            negated = line.startswith("!")
            if negated:
                line = line[1:]
            dir_only = line.endswith("/")
            line = line.rstrip("/")
            if line.startswith("/"):
                line = line[1:]
                if prefix not in (".", ""):
                    line = f"{prefix}/{line}"
            self.rules.append((line, negated, dir_only))

    def add_nested(self, path: Path) -> None:
        """Load a .gitignore found deeper in the tree."""
        self._load(path, path.parent)

    def ignored(self, relative: str, is_dir: bool = False) -> bool:
        relative = relative.replace("\\", "/")
        result = False
        for pattern, negated, dir_only in self.rules:
            if dir_only and not is_dir:
                continue
            if self._matches(relative, pattern):
                result = not negated
        return result

    @staticmethod
    def _matches(relative: str, pattern: str) -> bool:
        if fnmatch.fnmatch(relative, pattern):
            return True
        # An unanchored pattern matches at any depth.
        if "/" not in pattern:
            return any(
                fnmatch.fnmatch(part, pattern) for part in relative.split("/")
            )
        return fnmatch.fnmatch(relative, f"*/{pattern}")


def is_binary(path: Path, probe: int = 8192) -> bool:
    """Detect binaries by content rather than extension."""
    try:
        with path.open("rb") as handle:
            chunk = handle.read(probe)
    except OSError:
        return True
    return b"\x00" in chunk


def is_generated(text: str, lines: int) -> bool:
    """Detect minified or generated files by shape."""
    head = text[:2000]
    if _GENERATED_MARKER.search(head):
        return True
    # Mean line length over 400 characters means minified, not authored.
    return bool(lines and len(text) / lines > 400)


def is_test_file(relative: str, name: str) -> bool:
    parts = relative.replace("\\", "/").split("/")
    if any(part in TEST_DIRS for part in parts[:-1]):
        return True
    return any(fnmatch.fnmatch(name, pattern) for pattern in TEST_PATTERNS)


def scan(
    root: str | Path,
    languages: list[str] | None = None,
    max_file_bytes: int = 1_500_000,
    include_tests: bool = True,
    respect_gitignore: bool = True,
) -> ScanResult:
    """Walk a repository and collect the source files worth analysing."""
    base = Path(root).resolve()
    if not base.exists():
        raise FileNotFoundError(f"no such directory: {base}")

    result = ScanResult(root=base)
    wanted = set(languages) if languages else None
    rules = GitignoreRules(base) if respect_gitignore else None

    def skip(reason: str) -> None:
        result.skipped[reason] = result.skipped.get(reason, 0) + 1

    for dirpath, dirnames, filenames in os.walk(base):
        current = Path(dirpath)

        if (
            respect_gitignore
            and rules is not None
            and ".gitignore" in filenames
            and current != base
        ):
            rules.add_nested(current / ".gitignore")

        # Prune in place so os.walk does not descend.
        kept: list[str] = []
        for name in dirnames:
            if name in EXCLUDED_DIRS:
                skip(f"excluded directory: {name}")
                continue
            relative = str((current / name).relative_to(base))
            if rules is not None and rules.ignored(relative, is_dir=True):
                skip("gitignored directory")
                continue
            kept.append(name)
        dirnames[:] = sorted(kept)

        for name in sorted(filenames):
            path = current / name
            relative = str(path.relative_to(base)).replace("\\", "/")

            if any(fnmatch.fnmatch(name, pattern) for pattern in EXCLUDED_FILES):
                skip("generated or lock file")
                continue
            if rules is not None and rules.ignored(relative):
                skip("gitignored file")
                continue

            language = LANGUAGES.get(path.suffix.lower())
            if language is None:
                skip("unsupported extension")
                continue
            if wanted is not None and language not in wanted:
                skip("language filter")
                continue

            try:
                size = path.stat().st_size
            except OSError:
                skip("stat failed")
                continue
            if size > max_file_bytes:
                skip("file too large")
                continue
            if is_binary(path):
                skip("binary content")
                continue

            try:
                text = path.read_text(encoding="utf-8", errors="replace")
            except OSError:
                skip("read failed")
                continue

            line_count = text.count("\n") + (1 if text and not text.endswith("\n") else 0)
            if is_generated(text, line_count):
                skip("generated or minified content")
                continue

            test = is_test_file(relative, name)
            if test and not include_tests:
                skip("test file")
                continue

            result.files.append(
                SourceFile(
                    path=path,
                    relative=relative,
                    language=language,
                    size=size,
                    lines=line_count,
                    is_test=test,
                    text=text,
                )
            )

    result.files.sort(key=lambda f: f.relative)
    return result
